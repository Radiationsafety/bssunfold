# Numerical floors / guards -------------------------------------------------
_TINY = 1e-300         # absolute floor for denominators
_COUNT_FLOOR = 1e-10   # floor for forward-model counts (avoids div-by-zero)

# Relative penalty strengths scanned by the KS-based auto selection
# (beta_effective = beta_relative * mean column sum of RB).
AUTO_BETA_RELATIVE_GRID: tuple[float, ...] = (0.0, 1e-4, 1e-3, 1e-2, 1e-1)

_VALID_KNOT_SPACING = ("auto", "uniform", "log")


def _resolve_knot_spacing(knot_spacing: str, E: np.ndarray) -> str:
    """Resolve ``knot_spacing='auto'`` to ``'uniform'`` or ``'log'``.

    Log-spaced interior knots are used when the energy grid spans more
    than two decades (typical for Bonner sphere grids); otherwise knots
    are uniform in energy (the linear-binned setup of the paper).
    """
    if knot_spacing not in _VALID_KNOT_SPACING:
        raise ValueError(
            f"knot_spacing must be one of {_VALID_KNOT_SPACING}, got {knot_spacing!r}"
        )
    if knot_spacing != "auto":
        return knot_spacing
    ratio = float(E.max()) / float(E.min()) if E.size and E.min() > 0 else float("inf")
    return "log" if ratio > 100.0 else "uniform"


