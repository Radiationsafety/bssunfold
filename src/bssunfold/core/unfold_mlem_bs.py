def solve_mlem_bs_full(
    A: np.ndarray,
    b: np.ndarray,
    x0: np.ndarray | None = None,
    E_MeV: np.ndarray | None = None,
    n_basis: int | None = None,
    spline_order: int = 4,
    beta: float | None = None,
    beta_relative: float | None = None,
    knot_spacing: str = "auto",
    max_iterations: int = 1000,
    tolerance: float = 1e-6,
    auto_params: bool = False,
    ks_patience: int = 50,
) -> dict[str, Any]:
    """Solve the unfolding problem with MLEM-BS and return diagnostics.

    Parameters
    ----------
    A : np.ndarray
        Response matrix ``(I, J)``; ``J`` must match ``len(E_MeV)``.
    b : np.ndarray
        Measured readings ``(I,)`` (Poisson-distributed counts).
    x0 : np.ndarray, optional
        Initial spectrum guess ``(J,)``.  It is projected onto the
        non-negative B-spline sieve to obtain the starting coefficients.
        A flat spectrum is used when ``None``.
    E_MeV : np.ndarray
        Energy grid ``(J,)`` (MeV), required for the B-spline basis.
    n_basis : int, optional
        Dimension ``N_s`` of the B-spline space.  Default: ``None``
        selects ``max(spline_order + 1, min(n_energy_bins // 2, 40))``.
        The paper determines ``N_s`` from the first local minimum of
        ``K_S`` (e.g. ``N_s = 200`` for the fine stilbene bins); use
        ``auto_params=True`` to reproduce that selection automatically.
    spline_order : int, optional
        B-spline order ``p`` (degree ``p - 1``); the paper uses ``p = 4``
        (cubic).  Default: 4.
    beta : float, optional
        Absolute penalty strength of Eq. 4 (paper-scale dependent;
        the paper uses ``1.0e-17`` for its counting setup).
    beta_relative : float, optional
        Scale-aware alternative: effective ``beta = beta_relative *
        mean_s(sum_i (RB)_is)``.  Exactly one of ``beta`` /
        ``beta_relative`` may be given; default (both ``None``) is no
        penalty beyond the sieve.
    knot_spacing : str, optional
        Interior knot placement, ``"auto"`` (default: log knots when the
        energy grid spans more than two decades, uniform knots
        otherwise), ``"uniform"`` or ``"log"``.
    max_iterations : int, optional
        Iteration budget (default: 1000).  With ``auto_params=True`` the
        iteration count is itself selected by minimizing ``K_S``.
    tolerance : float, optional
        Relative coefficient-change convergence tolerance (default 1e-6).
    auto_params : bool, optional
        If True, ``N_s``, the penalty strength and the iteration count
        are selected by minimization of the ``K_S`` statistic (Eq. 6)
        over candidate grids, following the paper's optimization
        procedure (default: False).
    ks_patience : int, optional
        Early-stop patience (iterations without ``K_S`` improvement)
        used in the ``K_S``-minimizing mode (default: 50).

    Returns
    -------
    Dict[str, Any]
        Diagnostics dictionary with keys:

        * ``spectrum`` -- unfolded spectrum ``(J,)`` (non-negative);
        * ``coefficients`` -- B-spline coefficients ``(N_s,)``;
        * ``iterations``, ``converged`` -- iteration info;
        * ``ks_history`` -- per-iteration ``K_S`` values (Eq. 6);
        * ``ks_final`` -- ``K_S`` of the returned solution;
        * ``chi2_pearson`` -- Pearson chi-square of the final fit;
        * ``n_basis``, ``spline_order``, ``knot_spacing`` -- basis setup;
        * ``interior_knots`` -- interior knot sequence (MeV);
        * ``beta_effective``, ``beta_relative`` -- resolved penalty;
        * ``method`` -- always ``"MLEM-BS"``;
        * ``auto_selection`` -- (when ``auto_params=True``) dict with the
          candidate table and chosen parameters.
    """
    A = np.asarray(A, dtype=np.float64)
    b = np.asarray(b, dtype=np.float64).ravel()
    A, b, x0_in = validate_system(A, b, x0=x0, max_iterations=max_iterations,
                                  tolerance=tolerance)

    n_bins = A.shape[1]
    if E_MeV is None:
        raise ValueError("E_MeV is required to build the B-spline basis")
    E = np.asarray(E_MeV, dtype=np.float64).ravel()
    if E.size != n_bins:
        raise ValueError(
            f"Length of E_MeV ({E.size}) must match the number of "
            f"columns of A ({n_bins})"
        )
    if x0_in is None:
        x0_in = np.ones(n_bins) * 0.5
    knot_spacing = _resolve_knot_spacing(knot_spacing, E)

    # --- single configuration ------------------------------------------
    def _run_single(
        ns: int,
        beta_eff: float,
        beta_rel: float | None,
        max_iter: int,
        ks_mode: bool,
    ) -> dict[str, Any]:
        B = build_bspline_basis(E, ns, spline_order=spline_order,
                                knot_spacing=knot_spacing)
        RB = A @ B
        pen_mat = None
        if beta_eff != 0.0:
            D2 = second_difference_matrix(ns)
            pen_mat = 2.0 * (D2.T @ D2)
        b0 = _sieve_projection(B, x0_in)
        best_coef, iterations, converged, ks_history = _mlem_bs_iterate(
            RB,
            b,
            b0,
            pen_mat,
            beta_eff,
            max_iter,
            tolerance,
            ks_mode,
            ks_patience,
        )
        spectrum = B @ best_coef
        model = RB @ best_coef
        return {
            "spectrum": spectrum,
            "coefficients": best_coef,
            "iterations": int(iterations),
            "converged": bool(converged),
            "ks_history": ks_history,
            "ks_final": float(ks_history[-1]) if ks_history else float("inf"),
            "chi2_pearson": _chi2_pearson(b, model),
            "n_basis": int(ns),
            "spline_order": int(spline_order),
            "knot_spacing": knot_spacing,
            "interior_knots": _interior_knots(E, ns, spline_order, knot_spacing),
            "beta_effective": float(beta_eff),
            "beta_relative": beta_rel,
            "method": "MLEM-BS",
        }

    # --- auto selection of (N_s, beta, iterations) by minimizing K_S ----
    if auto_params:
        ns_grid = _auto_ns_grid(n_bins, spline_order)
        # cap scan iterations for tractability; final run uses the budget
        scan_iter = int(min(max_iterations, 400))
        candidates: list[dict[str, Any]] = []
        best: dict[str, Any] | None = None
        for ns in ns_grid:
            for rho in AUTO_BETA_RELATIVE_GRID:
                beta_eff = 0.0
                if rho > 0.0:
                    s_bar = float(np.mean((A @ build_bspline_basis(
                        E, ns, spline_order=spline_order,
                        knot_spacing=knot_spacing)).sum(axis=0)))
                    beta_eff = rho * s_bar
                res = _run_single(ns, beta_eff, rho if rho > 0 else 0.0,
                                  scan_iter, ks_mode=True)
                entry = {
                    "n_basis": ns,
                    "beta_relative": float(rho),
                    "ks": float(np.min(res["ks_history"])),
                    "ks_iteration": int(_argmin_index(res["ks_history"])),
                    "iterations": res["iterations"],
                }
                candidates.append(entry)
                if best is None or entry["ks"] < best["ks"]:
                    best = entry
        # final run with the full iteration budget in K_S-minimizing mode
        chosen_ns = int(best["n_basis"])
        chosen_rho = float(best["beta_relative"])
        beta_eff = 0.0
        if chosen_rho > 0.0:
            Bc = build_bspline_basis(E, chosen_ns, spline_order=spline_order,
                                     knot_spacing=knot_spacing)
            beta_eff = chosen_rho * float(np.mean((A @ Bc).sum(axis=0)))
        result = _run_single(chosen_ns, beta_eff,
                             chosen_rho if chosen_rho > 0 else 0.0,
                             max_iterations, ks_mode=True)
        result["auto_selection"] = {
            "candidates": candidates,
            "chosen": best,
            "ns_grid": ns_grid,
            "beta_relative_grid": list(AUTO_BETA_RELATIVE_GRID),
        }
        result["beta_relative"] = chosen_rho if chosen_rho > 0 else None
        result["beta_effective"] = float(beta_eff)
        return result

    # --- fixed parameters ----------------------------------------------
    if n_basis is None:
        n_basis = max(spline_order + 1, min(n_bins // 2, 40))
    beta_eff, beta_rel = _resolve_beta(beta, beta_relative, np.zeros((b.size, 1)))
    # resolve beta against the actual RB (s_bar depends on the basis)
    if beta_rel is not None:
        B = build_bspline_basis(E, int(n_basis), spline_order=spline_order,
                                knot_spacing=knot_spacing)
        beta_eff = beta_rel * float(np.mean((A @ B).sum(axis=0)))
    result = _run_single(int(n_basis), beta_eff, beta_rel, max_iterations,
                         ks_mode=False)
    return result


def solve_mlem_bs(
    A: np.ndarray,
    b: np.ndarray,
    x0: np.ndarray | None = None,
    E_MeV: np.ndarray | None = None,
    n_basis: int | None = None,
    spline_order: int = 4,
    beta: float | None = None,
    beta_relative: float | None = None,
    knot_spacing: str = "auto",
    max_iterations: int = 1000,
    tolerance: float = 1e-6,
    auto_params: bool = False,
    ks_patience: int = 50,
) -> tuple[np.ndarray, int, bool]:
    """Solve unfolding using the B-spline MLEM (MLEM-BS) algorithm.

    Convenience wrapper around :func:`solve_mlem_bs_full` returning the
    standard ``(spectrum, iterations, converged)`` tuple.  See the full
    solver for the meaning of the parameters.
    """
    result = solve_mlem_bs_full(
        A,
        b,
        x0=x0,
        E_MeV=E_MeV,
        n_basis=n_basis,
        spline_order=spline_order,
        beta=beta,
        beta_relative=beta_relative,
        knot_spacing=knot_spacing,
        max_iterations=max_iterations,
        tolerance=tolerance,
        auto_params=auto_params,
        ks_patience=ks_patience,
    )
    return result["spectrum"], result["iterations"], result["converged"]


# ---------------------------------------------------------------------------
# Poisson bootstrap confidence intervals (paper Eqs. 7-9)
# ---------------------------------------------------------------------------


def _poisson_bootstrap_ci(
    A: np.ndarray,
    x0: np.ndarray | None,
    E_MeV: np.ndarray,
    spectrum: np.ndarray,
    n_bootstrap: int,
    ci_alpha: float,
    random_state: int | None,
    solver_kwargs: dict[str, Any],
) -> dict[str, Any]:
    """Percentile bootstrap CI via Poisson resampling of the counts.

    Following Eqs. 7-9 of the paper: the backward-reconstructed counts
    ``n^(0) = A @ x^(0)`` (Eq. 8, with ``x^(0)`` the unfolded spectrum)
    define the Poisson means; each bootstrap replicate ``n*(b)`` (Eq. 9)
    is drawn independently as ``Poisson(n^(0))``, unfolded with the same
    solver configuration, and the 100(1-alpha)% interval is built from
    the alpha/2 and 1-alpha/2 quantiles of the bootstrap distribution
    (95% CI corresponds to alpha = 0.05).

    Note
    ----
    The interval quantifies the *counting-statistics* uncertainty of the
    unfolded spectrum (as in the paper, where the number of measured
    bins greatly exceeds ``N_s``).  When the system is strongly
    underdetermined (e.g. few Bonner sphere readings with a large
    basis), the systematic unfolding bias dominates and the replicate
    spread may understate the true uncertainty; in that regime prefer a
    smaller ``n_basis`` / ``auto_params=True`` selection, an informative
    ``initial_spectrum`` or an energy cutoff.

    Parameters
    ----------
    A : np.ndarray
        Response matrix ``(I, J)``.
    x0 : np.ndarray, optional
        Initial spectrum used for every replicate (same as the main
        solve); ``None`` uses a flat spectrum.
    E_MeV : np.ndarray
        Energy grid ``(J,)`` (MeV).
    spectrum : np.ndarray
        Unfolded spectrum ``x^(0)`` ``(J,)`` from the main solve.
    n_bootstrap : int
        Number of bootstrap replicates ``N_B``.
    ci_alpha : float
        Significance level (0.05 for a 95% interval).
    random_state : int, optional
        Seed for the Poisson resampling RNG.
    solver_kwargs : dict
        Additional keyword arguments forwarded to :func:`solve_mlem_bs`
        for every replicate (basis and penalty configuration).

    Returns
    -------
    Dict[str, Any]
        ``ci_low``, ``ci_high``, ``ci_level``, ``bootstrap_samples``,
        ``bootstrap_alpha``, ``bootstrap_mean``, ``bootstrap_std``.
    """
    n_bootstrap = int(n_bootstrap)
    if n_bootstrap < 1:
        raise ValueError(f"n_bootstrap must be >= 1, got {n_bootstrap}")
    if not 0.0 < float(ci_alpha) < 1.0:
        raise ValueError(f"ci_alpha must be in (0, 1), got {ci_alpha}")

    # Eq. 8: backward reconstruction of the initial count spectrum
    n0 = np.maximum(A @ np.asarray(spectrum, dtype=np.float64), 0.0)
    rng = np.random.default_rng(random_state)

    n_bins = int(np.asarray(spectrum).size)
    replicates = np.empty((n_bootstrap, n_bins), dtype=np.float64)
    for i in range(n_bootstrap):
        # Eq. 9: Poisson resampling preserving counting statistics
        n_star = rng.poisson(n0).astype(np.float64)
        x_rep, _, _ = solve_mlem_bs(A, n_star, x0=x0, E_MeV=E_MeV, **solver_kwargs)
        replicates[i] = np.asarray(x_rep, dtype=np.float64)

    ci_alpha = float(ci_alpha)
    ci_low = np.percentile(replicates, 100.0 * ci_alpha / 2.0, axis=0)
    ci_high = np.percentile(replicates, 100.0 * (1.0 - ci_alpha / 2.0), axis=0)
    return {
        "ci_low": ci_low,
        "ci_high": ci_high,
        "ci_level": float(1.0 - ci_alpha),
        "bootstrap_samples": n_bootstrap,
        "bootstrap_alpha": ci_alpha,
        "bootstrap_mean": replicates.mean(axis=0),
        "bootstrap_std": (
            replicates.std(axis=0, ddof=1) if n_bootstrap > 1 else np.zeros(n_bins)
        ),
    }


