"""B-spline MLEM unfolding method with sieve regularization (MLEM-BS).

Implementation of the MLEM-BS algorithm described in V. Mazankova,
L. Torokova, D. Trunec, Z. Kopecky, Z. Matej, ``Experimental Measurement
of Neutron Flux and Its Mathematical Data Processing``, Proceedings of the
5th International Conference CNDGS'2026, Brno, Czech Republic, 7-10
September 2026, ISSN 2538-8959, https://doi.org/10.47459/cndcgs.2026.61.

The method solves the discrete Fredholm integral equation of the first kind

    n_i = sum_j R_ij x_j,   i = 1..I,                       (Eq. 2)

with Poisson-distributed counts ``n_i`` by representing the sought
spectrum as a linear combination of B-spline basis functions

    x(E) = sum_s b_s B_s(E),   s = 1..N_s,

so that the effective system matrix becomes ``RB = R @ B`` and the
B-spline coefficients ``b_s`` are found with the regularized MLEM
iteration (MLEM-BS, Eq. 4 of the paper):

    b_s^(k+1) = b_s^(k) / (sum_i (RB)_is + beta * dP/db_s)
                * sum_i (RB)_is * n_i / (sum_s' (RB)_is' b_s'^(k)),

where the penalty (Eq. 5) suppresses noise influence,

    P(b) = ||D^(2) b||_2^2,      dP/db = 2 (D^(2))^T D^(2) b,

with ``D^(2)`` the second-derivative (second finite difference) matrix.
The solution is restricted to the B-spline sieve (non-negative
coefficients), following Z. Szkutnik, ``B-splines and discretization in an
inverse problem for Poisson processes``, Journal of Multivariate Analysis
93, 198-221 (2005) -- reference [7] of the paper.  Positivity is preserved
automatically by the multiplicative MLEM update started from a
non-negative sieve projection of the initial spectrum.

Following the paper, the number of iterations and the parameters ``N_s``
(B-spline space dimension) and ``beta`` (penalty strength) are selected by
minimization of the goodness-of-fit statistic (Eq. 6):

    K_S = | sum_i (n_i - sum_s (RB)_is b_s^(k))^2
            / sum_i sum_s (RB)_is b_s^(k)  -  1 |.

The paper also estimates confidence intervals of the unfolded spectrum
with a Poisson bootstrap (Eqs. 7-9): a synthetic ensemble of response
vectors is generated by resampling the backward-reconstructed counts
``n^(0) = R x^(0)`` from Poisson distributions, each replicate is unfolded,
and the 100(1-alpha)% interval is formed from the alpha/2 and 1-alpha/2
quantiles of the bootstrap distribution (95% CI corresponds to
alpha = 0.05).

Module API (standard bssunfold solver conventions):

* ``build_bspline_basis(E_MeV, n_basis, ...)`` -- B-spline design matrix;
* ``second_difference_matrix(n)`` -- the ``D^(2)`` penalty matrix;
* ``ks_statistic(b, model)`` -- the ``K_S`` statistic of Eq. 6;
* ``solve_mlem_bs(A, b, x0, E_MeV, ...)`` -- core solver returning
  ``(spectrum, iterations, converged)``;
* ``solve_mlem_bs_full(...)`` -- the same solver returning a rich
  diagnostics dictionary (``K_S`` history, effective beta, auto-selection
  table, ...);
* ``unfold_mlem_bs(...)`` -- Detector-facing wrapper (also exposed as
  ``Detector.unfold_mlem_bs``) with optional Poisson-bootstrap confidence
  intervals.

Scaling note
------------
The absolute penalty parameter ``beta`` of Eq. 4 is problem-scale
dependent (the paper uses ``beta = 1.0e-17`` for its counting setup).
For convenience this module additionally accepts ``beta_relative``,
which defines the effective penalty as ``beta = beta_relative * s_bar``
with ``s_bar`` the mean column sum of the effective matrix ``RB``, i.e.
the penalty gradient is measured relative to the MLEM sensitivity.
Exactly one of ``beta`` / ``beta_relative`` may be provided; with neither,
``beta = 0`` (pure sieve MLEM on the B-spline parameterization).
"""

