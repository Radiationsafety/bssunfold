def unfold_mlem_bs(
    detector_names: list[str],
    n_energy_bins: int,
    E_MeV: np.ndarray,
    sensitivities: dict[str, np.ndarray],
    cc_icrp116: dict[str, np.ndarray],
    save_result_callback,
    readings: dict[str, float],
    initial_spectrum: np.ndarray | None = None,
    n_basis: int | None = None,
    spline_order: int = 4,
    beta: float | None = None,
    beta_relative: float | None = None,
    knot_spacing: str = "auto",
    max_iterations: int = 1000,
    tolerance: float = 1e-6,
    auto_params: bool = False,
    bootstrap_ci: bool = False,
    n_bootstrap: int = 100,
    ci_alpha: float = 0.05,
    calculate_errors: bool = False,
    noise_level: float = 0.01,
    n_montecarlo: int = 100,
    save_result: bool = False,
    random_state: int | None = None,
) -> dict[str, Any]:
    """Unfold using the B-spline MLEM method with regularization (MLEM-BS).

    Detector-facing wrapper of the Mazankova et al. MLEM-BS algorithm
    (CNDGS'2026, https://doi.org/10.47459/cndcgs.2026.61): the spectrum
    is represented in a B-spline basis (sieve restriction to
    non-negative coefficients, Szkutik 2005) and the coefficients are
    updated with the regularized MLEM iteration (Eq. 4) with the
    second-derivative penalty ``P(b) = ||D^(2) b||_2^2`` (Eq. 5).
    Optionally, the number of iterations, ``N_s`` and the penalty
    strength are selected by minimizing the ``K_S`` statistic (Eq. 6),
    and confidence intervals are estimated with a Poisson bootstrap
    (Eqs. 7-9).

    Parameters
    ----------
    detector_names : List[str]
        Names of available detectors.
    n_energy_bins : int
        Number of energy bins.
    E_MeV : np.ndarray
        Energy grid (MeV).
    sensitivities : Dict[str, np.ndarray]
        Detector sensitivity arrays.
    cc_icrp116 : Dict[str, np.ndarray]
        ICRP-116 conversion coefficients.
    save_result_callback : callable
        Callback to save result to history.
    readings : Dict[str, float]
        Detector readings.
    initial_spectrum : Optional[np.ndarray], optional
        Initial spectrum guess; projected onto the non-negative
        B-spline sieve.  Flat when ``None``.
    n_basis : Optional[int], optional
        Dimension ``N_s`` of the B-spline space; default ``None``
        selects ``max(spline_order + 1, min(n_energy_bins // 2, 40))``.
    spline_order : int, optional
        B-spline order ``p`` (default: 4, cubic, as in the paper).
    beta : Optional[float], optional
        Absolute penalty strength (paper Eq. 4; problem-scale
        dependent).
    beta_relative : Optional[float], optional
        Scale-aware penalty strength: effective ``beta = beta_relative
        * mean column sum of RB``.  Mutually exclusive with ``beta``.
    knot_spacing : str, optional
        Interior knot placement: ``"auto"`` (default; log knots for
        grids spanning more than two decades, uniform knots otherwise),
        ``"uniform"`` or ``"log"`` for logarithmically binned grids.
    max_iterations : int, optional
        Iteration budget (default: 1000).
    tolerance : float, optional
        Relative coefficient-change tolerance (default: 1e-6).
    auto_params : bool, optional
        Select iteration count, ``N_s`` and penalty strength by
        minimizing ``K_S`` (Eq. 6), following the paper's optimization
        procedure (default: False).
    bootstrap_ci : bool, optional
        Estimate confidence intervals with the Poisson bootstrap of
        Eqs. 7-9 (default: False).
    n_bootstrap : int, optional
        Number of bootstrap replicates (default: 100).
    ci_alpha : float, optional
        Significance level for the CI (default: 0.05 -> 95% interval).
    calculate_errors : bool, optional
        Calculate Monte-Carlo errors (default: False).
    noise_level : float, optional
        Noise level for Monte-Carlo (default: 0.01).
    n_montecarlo : int, optional
        Number of Monte-Carlo samples (default: 100).
    save_result : bool, optional
        Save result to history (default: False).
    random_state : int, optional
        Random seed for the bootstrap resampling.

    Returns
    -------
    Dict[str, Any]
        Standardized unfolding results dictionary enriched with the
        method diagnostics (``ks_history``, ``ks_final``,
        ``chi2_pearson``, ``n_basis``, ``spline_order``,
        ``knot_spacing``, ``interior_knots``, ``beta_effective``,
        ``beta_relative`` and, when ``auto_params=True``,
        ``auto_selection``; when ``bootstrap_ci=True``, ``ci_low``,
        ``ci_high``, ``ci_level``, ``bootstrap_samples``,
        ``bootstrap_alpha``, ``bootstrap_mean``, ``bootstrap_std``).
    """
    diag: dict[str, Any] = {}

    def solve_wrapper(A_mat: np.ndarray, b_vec: np.ndarray, **kwargs):
        out = solve_mlem_bs_full(
            A_mat,
            b_vec,
            x0=kwargs.get("x0"),
            E_MeV=E_MeV,
            n_basis=n_basis,
            spline_order=spline_order,
            beta=beta,
            beta_relative=beta_relative,
            knot_spacing=knot_spacing,
            max_iterations=max_iterations,
            tolerance=tolerance,
            auto_params=auto_params,
        )
        diag.update(
            ks_history=out["ks_history"],
            ks_final=out["ks_final"],
            chi2_pearson=out["chi2_pearson"],
            n_basis=out["n_basis"],
            spline_order=out["spline_order"],
            knot_spacing=out["knot_spacing"],
            interior_knots=out["interior_knots"],
            beta_effective=out["beta_effective"],
            beta_relative=out["beta_relative"],
            coefficients=out["coefficients"],
        )
        if "auto_selection" in out:
            diag["auto_selection"] = out["auto_selection"]
        return out["spectrum"], out["iterations"], out["converged"]

    x0_default = np.ones(n_energy_bins) * 0.5

    output = run_unfolding(
        detector_names=detector_names,
        n_energy_bins=n_energy_bins,
        E_MeV=E_MeV,
        sensitivities=sensitivities,
        cc_icrp116=cc_icrp116,
        save_result_callback=save_result_callback,
        readings=readings,
        initial_spectrum=initial_spectrum,
        default_initial=x0_default,
        solve_func=solve_wrapper,
        solve_kwargs={},
        method_name="MLEM-BS",
        extra_output=diag,
        calculate_errors=calculate_errors,
        noise_level=noise_level,
        n_montecarlo=n_montecarlo,
        random_state=random_state,
        save_result=save_result,
    )

    if bootstrap_ci:
        from ._base_unfolder import _build_system, _normalize_initial

        A_sys, _, _ = _build_system(readings, detector_names, sensitivities)
        x0_main = _normalize_initial(initial_spectrum, x0_default, n_energy_bins)
        # reuse the configuration selected/used by the main solve so that
        # every replicate is unfolded with the same algorithm settings
        solver_kwargs: dict[str, Any] = {
            "n_basis": int(diag.get("n_basis") or max(
                spline_order + 1, min(n_energy_bins // 2, 40))),
            "spline_order": int(diag.get("spline_order", spline_order)),
            "beta": float(diag.get("beta_effective") or 0.0),
            "knot_spacing": diag.get("knot_spacing", knot_spacing),
            "max_iterations": int(max_iterations),
            "tolerance": float(tolerance),
        }
        boot = _poisson_bootstrap_ci(
            A_sys,
            x0=x0_main,
            E_MeV=E_MeV,
            spectrum=output["spectrum"],
            n_bootstrap=n_bootstrap,
            ci_alpha=ci_alpha,
            random_state=random_state,
            solver_kwargs=solver_kwargs,
        )
        output.update(boot)

    return output
