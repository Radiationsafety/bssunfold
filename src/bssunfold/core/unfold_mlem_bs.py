# Core MLEM-BS iteration
# ---------------------------------------------------------------------------


def _sieve_projection(B: np.ndarray, x0: np.ndarray) -> np.ndarray:
    """Project an initial spectrum onto the non-negative B-spline sieve.

    Solves ``min ||B b - x0||_2`` subject to ``b >= 0`` (NNLS).  Falls
    back to an unconstrained least-squares fit clipped at zero when the
    NNLS solver fails.  A constant spectrum maps to constant
    coefficients through the partition-of-unity property.
    """
    ns = B.shape[1]
    mean_x0 = float(np.mean(x0)) if x0.size else 0.0
    fallback = np.full(ns, max(mean_x0, _COUNT_FLOOR))
    try:
        b0, _ = nnls(B, x0)
    except Exception:  # pragma: no cover - numerical fallback
        b0, *_ = np.linalg.lstsq(B, x0, rcond=None)
        b0 = np.maximum(b0, 0.0)
    if not np.all(np.isfinite(b0)):
        return fallback
    if not np.any(b0 > 0):
        # pathological all-zero projection: keep the iteration alive
        return np.full(ns, max(mean_x0, _COUNT_FLOOR))
    return b0


def _resolve_beta(
    beta: float | None,
    beta_relative: float | None,
    RB: np.ndarray,
) -> tuple[float, float | None]:
    """Resolve absolute vs relative penalty strength.

    Returns ``(beta_effective, beta_relative)``.  Exactly one of the two
    inputs may be non-``None``; ``None``/``None`` means no penalty.
    """
    if beta is not None and beta_relative is not None:
        raise ValueError(
            "Provide either 'beta' (absolute, paper Eq. 4) or "
            "'beta_relative' (scaled by mean sensitivity), not both"
        )
    if beta_relative is not None:
        beta_relative = float(beta_relative)
        if beta_relative < 0:
            raise ValueError(f"beta_relative must be >= 0, got {beta_relative}")
        s_bar = float(np.mean(RB.sum(axis=0))) if RB.size else 0.0
        return beta_relative * s_bar, beta_relative
    beta_eff = 0.0 if beta is None else float(beta)
    if beta_eff < 0:
        raise ValueError(f"beta must be >= 0, got {beta_eff}")
    return beta_eff, None


def _mlem_bs_iterate(
    RB: np.ndarray,
    b: np.ndarray,
    b_coef: np.ndarray,
    pen_mat: np.ndarray | None,
    beta: float,
    max_iterations: int,
    tolerance: float,
    ks_min_mode: bool,
    ks_patience: int,
) -> tuple[np.ndarray, int, bool, list[float], np.ndarray]:
    """Run the MLEM-BS iteration (Eq. 4) on the effective system.

    Parameters
    ----------
    RB : np.ndarray
        Effective response matrix ``(I, N_s)`` (``R @ B``).
    b : np.ndarray
        Measured counts ``(I,)``.
    b_coef : np.ndarray
        Initial non-negative B-spline coefficients ``(N_s,)``.
    pen_mat : np.ndarray or None
        Matrix ``2 (D^(2))^T D^(2)`` (``None`` when ``beta == 0``).
    beta : float
        Absolute penalty strength (already resolved).
    max_iterations : int
        Iteration budget.
    tolerance : float
        Relative-change convergence tolerance on the coefficients.
    ks_min_mode : bool
        When True, track the iterate with the minimal ``K_S`` and stop
        after ``ks_patience`` iterations without improvement (the paper
        selects the iteration number by minimizing ``K_S``).
    ks_patience : int
        Patience (iterations) for the ``K_S``-based early stop.

    Returns
    -------
    Tuple[np.ndarray, int, bool, List[float]]
        ``(best_coefficients, iterations, converged, ks_history)`` where
        ``best_coefficients`` is the iterate with the minimal ``K_S``
        (in ``ks_min_mode``) or simply the last iterate otherwise.
    """
    s_s = RB.sum(axis=0)  # MLEM sensitivity: sum_i (RB)_is
    s_s_safe = np.maximum(s_s, _TINY)

    best_coef = b_coef.copy()
    best_ks = ks_statistic(b, RB @ b_coef)
    ks_history: list[float] = [best_ks]
    converged = False
    iterations = 0

    for k in range(max_iterations):
        # forward projection: sum_s' (RB)_is' b_s'^(k)
        fwd = RB @ b_coef
        fwd = np.maximum(fwd, _COUNT_FLOOR)
        ratio = b / fwd

        # multiplicative ML correction
        correction = RB.T @ ratio

        # penalized denominator: sum_i (RB)_is + beta * dP/db_s  (Eq. 4)
        if beta != 0.0 and pen_mat is not None:
            grad_P = pen_mat @ b_coef
            denom = s_s + beta * grad_P
            # one-step-late guard: fall back to the unpenalized
            # sensitivity where the penalty gradient would flip the
            # denominator non-positive (standard OSL safeguard)
            denom = np.where(denom > _TINY, denom, s_s_safe)
        else:
            denom = s_s_safe
        denom = np.maximum(denom, _TINY)

        b_new = b_coef * (correction / denom)
        b_new = np.maximum(b_new, 0.0)  # B-spline sieve: b_s >= 0

        iterations = k + 1

        # K_S statistic of the new iterate (Eq. 6)
        fwd_new = RB @ b_new
        ks = ks_statistic(b, fwd_new)
        ks_history.append(ks)

        if ks_min_mode:
            if ks < best_ks:
                best_ks = ks
                best_coef = b_new.copy()
            elif (k + 1) - _argmin_index(ks_history) >= ks_patience:
                b_coef = b_new
                break
        else:
            best_coef = b_new

        # convergence on relative coefficient change
        diff = np.linalg.norm(b_new - b_coef) / (np.linalg.norm(b_coef) + _TINY)
        b_coef = b_new
        if diff < tolerance:
            converged = True
            break

    return best_coef, iterations, converged, ks_history


def _argmin_index(values: list[float]) -> int:
    """Index of the minimum of a list (ignoring NaN as never minimal)."""
    best_i = 0
    best_v = float("inf")
    for i, v in enumerate(values):
        if np.isfinite(v) and v < best_v:
            best_v = v
            best_i = i
    return best_i


