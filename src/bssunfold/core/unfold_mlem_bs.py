def _auto_ns_grid(
    n_energy_bins: int,
    spline_order: int,
    n_points: int = 8,
) -> list[int]:
    """Candidate ``N_s`` grid for the KS-based auto selection.

    Log-spaced candidate sizes between ``max(spline_order + 1, 8)`` and
    ``min(n_energy_bins, 150)`` (the B-spline space is not usefully larger
    than the data grid for Bonner sphere problems).
    """
    lo = max(spline_order + 1, 8)
    hi = max(min(int(n_energy_bins), 150), lo)
    if hi <= lo:
        return [lo]
    grid = np.geomspace(lo, hi, n_points)
    sizes = sorted({int(round(v)) for v in grid} | {lo, hi})
    return [v for v in sizes if v >= spline_order + 1]


def _interior_knots(
    E: np.ndarray,
    n_basis: int,
    spline_order: int,
    knot_spacing: str,
) -> np.ndarray:
    """Reconstruct the interior knot sequence of the clamped basis.

    ``knot_spacing`` must already be resolved (not ``"auto"``).
    """
    n_interior = int(n_basis) - int(spline_order)
    if n_interior <= 0:
        return np.empty(0)
    emin, emax = float(E[0]), float(E[-1])
    if knot_spacing == "log":
        return np.geomspace(emin, emax, n_interior + 2)[1:-1]
    return np.linspace(emin, emax, n_interior + 2)[1:-1]


def _chi2_pearson(b: np.ndarray, model: np.ndarray) -> float:
    """Pearson chi-square ``sum_i (n_i - model_i)^2 / model_i`` (diagnostic)."""
    b = np.asarray(b, dtype=np.float64).ravel()
    model = np.asarray(model, dtype=np.float64).ravel()
    mask = model > _COUNT_FLOOR
    if not np.any(mask):
        return float("inf")
    resid = b[mask] - model[mask]
    return float(np.sum(resid * resid / model[mask]))


