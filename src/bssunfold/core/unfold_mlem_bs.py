def build_bspline_basis(
    E_MeV: np.ndarray,
    n_basis: int,
    spline_order: int = 4,
    knot_spacing: str = "auto",
) -> np.ndarray:
    """Build the B-spline basis (design) matrix ``B`` on an energy grid.

    The spectrum is represented as ``x(E) = B(E) @ b`` where ``B`` is the
    matrix of B-spline basis functions evaluated at the energy bins
    (the ``B_is`` matrix of Eq. 4 context in the paper).  Clamped knot
    vectors are used, so the spline reproduces the boundary energies
    exactly and the basis forms a partition of unity (a constant
    coefficient vector reproduces a constant spectrum).

    Parameters
    ----------
    E_MeV : np.ndarray
        Energy grid (MeV), 1D, positive, strictly increasing.
    n_basis : int
        Number of B-spline basis functions ``N_s`` (dimension of the
        B-spline space).  Must be ``>= spline_order``.
    spline_order : int, optional
        Order ``p`` of the B-splines (degree = order - 1).  The paper
        uses ``p = 4`` (cubic splines).  Default: 4.
    knot_spacing : str, optional
        Placement of the interior knots: ``"auto"`` (default; log knots
        when the grid spans more than two decades, uniform knots
        otherwise), ``"uniform"`` (knots linear in energy, as
        appropriate for linear-binned spectra like the stilbene data of
        the paper) or ``"log"`` (knots uniform in log-energy,
        appropriate for logarithmically binned Bonner sphere grids
        spanning several decades).

    Returns
    -------
    np.ndarray
        Dense ``(len(E_MeV), n_basis)`` design matrix with non-negative
        entries (B-splines are non-negative).
    """
    E = np.asarray(E_MeV, dtype=np.float64).ravel()
    if E.ndim != 1 or E.size < 2:
        raise ValueError(
            f"E_MeV must be a 1D array with >= 2 points, got shape {E.shape}"
        )
    if not np.all(np.isfinite(E)):
        raise ValueError("E_MeV contains non-finite values")
    if np.any(np.diff(E) <= 0):
        raise ValueError("E_MeV must be strictly increasing")
    if np.any(E <= 0):
        raise ValueError("E_MeV must contain positive energies")

    n_basis = int(n_basis)
    spline_order = int(spline_order)
    if spline_order < 2 or spline_order > 8:
        raise ValueError(f"spline_order must be in [2, 8], got {spline_order}")
    if n_basis < spline_order:
        raise ValueError(
            f"n_basis (N_s = {n_basis}) must be >= spline_order "
            f"(p = {spline_order}) for a clamped B-spline basis"
        )
    if knot_spacing not in _VALID_KNOT_SPACING:
        raise ValueError(
            f"knot_spacing must be one of {_VALID_KNOT_SPACING}, got {knot_spacing!r}"
        )

    degree = spline_order - 1
    emin = float(E[0])
    emax = float(E[-1])
    knot_spacing = _resolve_knot_spacing(knot_spacing, E)

    n_interior = n_basis - spline_order  # from len(t) = n_basis + degree + 1
    if n_interior > 0:
        if knot_spacing == "log":
            interior = np.geomspace(emin, emax, n_interior + 2)[1:-1]
        else:
            interior = np.linspace(emin, emax, n_interior + 2)[1:-1]
    else:
        interior = np.empty(0)

    t = np.concatenate(
        (
            np.full(spline_order, emin),
            interior,
            np.full(spline_order, emax),
        )
    )

    # design_matrix requires x within [t[k], t[N-k-1]]; clip for float fuzz
    x_clipped = np.clip(E, emin, emax)
    Bm = BSpline.design_matrix(x_clipped, t, degree, extrapolate=False)
    return np.asarray(Bm.todense(), dtype=np.float64)


def second_difference_matrix(n: int) -> np.ndarray:
    """Return the second-derivative (second finite difference) matrix ``D^(2)``.

    Row ``i`` holds ``[.., 1, -2, 1, ..]`` so that ``(D^(2) b)_i``
    approximates the second derivative of the coefficient sequence.
    Used in the penalty functional ``P(b) = ||D^(2) b||_2^2`` (Eq. 5).

    Parameters
    ----------
    n : int
        Length of the coefficient vector (``n >= 3``).

    Returns
    -------
    np.ndarray
        ``(n - 2, n)`` matrix.
    """
    n = int(n)
    if n < 3:
        raise ValueError(f"second_difference_matrix requires n >= 3, got {n}")
    D = np.zeros((n - 2, n), dtype=np.float64)
    for i in range(n - 2):
        D[i, i] = 1.0
        D[i, i + 1] = -2.0
        D[i, i + 2] = 1.0
    return D


def ks_statistic(b: np.ndarray, model: np.ndarray) -> float:
    """Compute the ``K_S`` goodness-of-fit statistic of Eq. 6.

    ``K_S = | sum_i (n_i - model_i)^2 / sum_i model_i - 1 |``.

    The number of iterations, ``N_s`` and ``beta`` are selected by
    minimizing this statistic (paper, section 3).

    Parameters
    ----------
    b : np.ndarray
        Measured counts vector ``n``.
    model : np.ndarray
        Forward-model counts ``RB @ b_s^(k)``.

    Returns
    -------
    float
        Non-negative ``K_S`` value.
    """
    b = np.asarray(b, dtype=np.float64).ravel()
    model = np.asarray(model, dtype=np.float64).ravel()
    denom = float(np.sum(model))
    if denom <= _TINY:
        return float("inf")
    resid = b - model
    return abs(float(np.sum(resid * resid)) / denom - 1.0)


